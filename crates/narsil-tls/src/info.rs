#[cfg(test)]
mod warnung_tests {
    use super::*;

    /// added 03.10.2026, Rolle TLS. **DIE DREI FAELLE VON FIREFOX**, und jeder
    /// ist **ein** Fehler, den `kette_pruefen` auch wirklich liefert.
    ///
    /// **UND DIE ZEITEN SIND ERSETZT, nicht geraten:** die Testzertifikate aus
    /// `x509::bauen` haben eine Geltigkeit, die von der Uhr des Rechners
    /// unabhaengig ist. Deshalb konstruiere ich den Fehler **von Hand** mit
    /// festen Werten — sonst waere der Test eines Tages still rot, weil ein
    /// Testzertifikat abgelaufen ist. **Das ist kein Testfehler, sondern eine
    /// Testwaechterfrage**, und die Antwort ist: feste Zeiten.
    #[test]
    fn die_drei_faelle_von_firefox_werden_benannt() {
        let _de = narsil_i18n::scoped(narsil_i18n::Language::German); // the German wording of the page
        // 1) ABGELAUFEN: jetzt > bis.
        let w = zertifikatswarnung(
            &KetteFehler::AusserhalbDerGueltigkeit {
                von: 1_700_000_000,
                bis: 1_800_000_000,
                jetzt: 1_900_000_000,
            },
            "expired.badssl.com",
        );
        assert_eq!(w.art, WarnArt::Abgelaufen);
        assert!(w.erklaerung.contains("abgelaufen"), "{}", w.erklaerung);
        // added 03.10.2026, TLS: **DER TECHNISCHE TEXT BLEIBT WOERTLICH** — er
        // ist fuer den aufgeklappten Bereich, und dort gehoert die Tatsache und
        // nicht eine Zusammenfassung. GEMESSEN, dass er die **Zeiten**
        // enthaelt, die der Fehler nennt: der Benutzer soll sehen, **wann**.
        assert!(w.technisch.contains("1700000000"), "{}", w.technisch);

        // 2) FALSCHER HOST.
        let w = zertifikatswarnung(&KetteFehler::HostnamePasstNicht, "wrong.host.badssl.com");
        assert_eq!(w.art, WarnArt::FalscherHost);
        assert!(w.erklaerung.contains("anderen Namen"), "{}", w.erklaerung);
        assert_eq!(w.host, "wrong.host.badssl.com");

        // 3) SELBSTSIGNIERT / UNBEKANNTE AUSSTELLERIN.
        let w = zertifikatswarnung(&KetteFehler::KeinAussteller, "self-signed.badssl.com");
        assert_eq!(w.art, WarnArt::UnbekannteAusstellerin);
        assert!(
            w.erklaerung.contains("unbekannt"),
            "die Ausstellerin wird benannt: {}",
            w.erklaerung
        );
        // UND DIE EHRENTLICHKEIT, die der Test festnagelt: der Text sagt
        // **nicht** „selbstsigniert", weil `KeinAussteller` das **nicht** weiss.
        // Wer das hier aendert, muss die Daten mitbringen, aus denen man es
        // ableiten koennte.
        assert!(
            !w.erklaerung.contains("selbstsigniertes Zertifikat ist"),
            "der Text behauptet keine Selbstsignierung, die er nicht belegen kann"
        );
    }

    /// added 03.10.2026, Rolle TLS. **DIE RICHTUNG DER GELTIGKEIT ZAEHLT** — und
    /// das ist kein Detail, sondern **zwei verschiedene Ratschlaege**.
    ///
    /// **GEMESSEN, warum der Test existiert:** dieselbe Fehlervariante
    /// (`AusserhalbDerGueltigkeit`) traegt **drei** Faelle, und ohne die
    /// Unterscheidung wuerde ein **noch nicht gueltiges** Zertifikat als
    /// „abgelaufen" gemeldet — und der Benutzer wuerde seine **Uhr** pruefen
    /// statt zu warten.
    #[test]
    fn noch_nicht_gueltig_ist_nicht_abgelaufen() {
        let _de = narsil_i18n::scoped(narsil_i18n::Language::German); // the German wording of the page
        let w = zertifikatswarnung(
            &KetteFehler::AusserhalbDerGueltigkeit {
                von: 2_000_000_000,
                bis: 2_100_000_000,
                jetzt: 1_900_000_000,
            },
            "kunftig.test",
        );
        assert_eq!(w.art, WarnArt::NochNichtGueltig);
        assert!(w.erklaerung.contains("Uhr"), "{}", w.erklaerung);

        // UND DER DRITTE FALL, den die Variante auch traegt: `jetzt` liegt
        // **zwischen** `von` und `bis`. Dann ist der Fehler **nicht**
        // erklärbar — und die ehrliche Kategorie ist „Kette kaputt", nicht
        // „abgelaufen".
        let w = zertifikatswarnung(
            &KetteFehler::AusserhalbDerGueltigkeit {
                von: 1_000,
                bis: 3_000,
                jetzt: 2_000,
            },
            "widerspruch.test",
        );
        assert_eq!(
            w.art,
            WarnArt::KetteKaputt,
            "ein 'ausserhalb' mit 'jetzt' innerhalb ist ein Widerspruch"
        );
    }

    /// added 03.10.2026, Rolle TLS: **JEDE VARIANTE HAT EINE KATEGORIE**, und
    /// das ist der Test gegen **stille** Luecken: wer eine Variante zu
    /// `KetteFehler` dazunimmt, bekommt hier einen **roten** Test, statt dass
    /// seine neue Variante still in `Sonstiges` landet.
    ///
    /// **WARUM DAS WICHTIG IST, und es ist ein Befund aus diesem Testbau:** mit
    /// einem `_ => Sonstiges`-Zweig ist **jede** zukuenftige Variante
    /// automatisch abgedeckt — und **genau das** macht die Warnseite unbrauchbar,
    /// denn sie nennt dann einen Grund, den sie nicht kennt.
    #[test]
    fn jede_kettefehler_variante_ist_einer_kategorie_zugeordnet() {
        let proben: Vec<(KetteFehler, WarnArt)> = vec![
            (
                KetteFehler::AusserhalbDerGueltigkeit {
                    von: 1,
                    bis: 2,
                    jetzt: 9,
                },
                WarnArt::Abgelaufen,
            ),
            (KetteFehler::HostnamePasstNicht, WarnArt::FalscherHost),
            (KetteFehler::KeinAussteller, WarnArt::UnbekannteAusstellerin),
            (
                KetteFehler::SignaturPasstNicht { stelle: 1 },
                WarnArt::UnbekannteAusstellerin,
            ),
            (KetteFehler::ZuTief { erlaubt: 10 }, WarnArt::KetteKaputt),
            (KetteFehler::HashNichtUnterstuetzt, WarnArt::KetteKaputt),
            (
                KetteFehler::ZertifikatUngueltig {
                    index: 0,
                    grund: "x".into(),
                },
                WarnArt::KetteKaputt,
            ),
        ];
        for (fehler, erwartet) in proben {
            assert_eq!(
                zertifikatswarnung(&fehler, "h.test").art,
                erwartet,
                "Falsch zugeordnet: {fehler}"
            );
        }
    }
}
