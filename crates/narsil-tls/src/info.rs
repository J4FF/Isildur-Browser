/// added 03.10.2026, TLS. **WARUM EINE EIGENE FEHLERFORM.** Die Funktion kann
/// zwei Dinge nicht, die beide ein `String` verlangen wuerden: `zertifikat_lesen`
/// liefert einen `X509Fehler` mit **Reichweite** (der Serialisierung), und der
/// Aufrufer muss wissen, **welches** Zertifikat der Kette es nicht lesen konnte.
/// Ohne die Stelle waere die Meldung „Zertifikat kaputt“ bei einer Kette von
/// vier — und die Kette wird in der Anzeige **nach Index** angesprochen.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum InfoFehler {
    /// Die Kette war leer. Das ist **kein** Lesefehler: `TlsVerbindung::kette()`
    /// liefert nach dem Handshake nie leer, und ein leeres Ergebnis heisst
    /// „die Verbindung kam ohne Zertifikat zustande“ — ein Fehler, der im
    /// Handshake liegen muss, nicht hier.
    KetteLeer,
    /// added 03.10.2026, TLS. `stelle` ist der **Index in der Kette** (0 =
    /// Blatt) und `grund` der Text aus `X509Fehler`.
    ZertifikatUnlesbar { stelle: usize, grund: String },
}

impl std::fmt::Display for InfoFehler {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            InfoFehler::KetteLeer => write!(f, "die Zertifikatskette ist leer"),
            InfoFehler::ZertifikatUnlesbar { stelle, grund } => {
                write!(f, "Zertifikat {stelle} der Kette ist unlesbar: {grund}")
            }
        }
    }
}

/// added 03.10.2026, TLS. **EIN ZERTIFIKAT ALS ANGABE**, Blatt zuerst.
///
/// **UND JEDES FELD IST EINE Tatsache, KEIN Urteil** — siehe den Kopf der
/// Datei. `gueltig` heisst „`jetzt` liegt im Zeitraum“, nicht „dem darf man
/// trauen“.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ZertifikatInfo {
    /// Der Index in der Kette. **0 ist das Blatt** (RFC 8446 4.4.2: „the
    /// first certificate … contains the end-entity certificate“), und
    /// `ist_blatt` sagt dasselbe noch einmal als Flag — redundant, aber die
    /// Anzeige fragt nicht nach Indizes, sondern danach, **welches Zertifikat
    /// das Serverzertifikat ist**.
    pub stelle: usize,
    /// `true` fuer das Blatt.
    pub ist_blatt: bool,
    /// Der Inhaber als Text nach RFC 4514 (`x509::name_als_text`).
    pub inhaber: String,
    /// Der Aussteller als Text nach RFC 4514.
    pub aussteller: String,
    /// Die Seriennummer als **HEX, gross** — `x509::integer_als_bytes` hat die
    /// fuehrende Null schon entfernt, das Feld ist also die Zahl in der
    /// Form, in der sie im Zertifikat steht.
    pub seriennummer: String,
    /// `notBefore` in Sekunden seit 1970.
    pub gueltig_von: i64,
    /// `notAfter` in Sekunden seit 1970.
    pub gueltig_bis: i64,
    /// `notBefore` als Text (siehe [`zeit_als_text`]).
    pub gueltig_von_text: String,
    /// `notAfter` als Text.
    pub gueltig_bis_text: String,
    /// added 03.10.2026, TLS. **LIEGT `jetzt` IM ZEITRAUM?** Beide Grenzen
    /// sind **einschliesslich** (RFC 5280 4.1.2.5), und die Rechnung macht
    /// `Gueltigkeit::enthaelt` — hier wird sie **nicht** wiederholt.
    pub gueltig: bool,
    /// `basicConstraints.cA` — **kein** Urteil, die Angabe selbst.
    pub ist_ca: bool,
    /// added 03.10.2026, TLS. **DER SCHLUESSELALGORITHMUS ALS TEXT**, und
    /// nicht die OID: `EC`, `RSA` oder `unbekannt`.
    pub schluessel_alg: &'static str,
    /// added 03.10.2026, TLS. **DIE BITZAHL, ODER `None`.** `None` heisst
    /// „nicht bekannt“ und ist **nicht** 0: bei unbekanntem Schluessel gibt es
    /// keine Bitzahl, und eine 0 waere eine erfundene.
    pub schluessel_bit: Option<usize>,
    /// added 03.10.2026, TLS. **DIE KURVE, NUR BEI EC** — `None` bei RSA.
    pub kurve: Option<&'static str>,
    /// Der Signaturalgorithmus als Text (`ecdsa-with-SHA256`).
    pub signatur: &'static str,
    /// added 03.10.2026, TLS. **DIE `subjectAltName`-DNS-Namen.** Das ist der
    /// **einzige** Namensnachweis, den `traegt_hostnamen` benutzt, wenn ein SAN
    /// da ist — die Anzeige zeigt deshalb **diese** Liste und nicht den CN, der
    /// daneben stehen darf und oft etwas anderes sagt.
    pub namen: Vec<String>,
    /// Die `rfc822Name`-Eintraege des SAN als Text.
    pub email: Vec<String>,
    /// added 03.10.2026, TLS. **DIE `iPAddress`-EintRAEGE ALS TEXT**, und der
    /// Grund fuer die Umrechnung steht bei `zeit_als_text`: RFC 5280 4.2.1.6
    /// definiert sie als **Bytes**, weil eine Adresse viele Schreibweisen hat.
    /// Fuer die Anzeige wird die **IPv4-Form mit Punkten** bzw. die
    /// **IPv6-Form mit Doppelpunkten** (RFC 4291 2.2) benutzt — die Form, in
    /// der der Nutzer die Adresse selbst getippt haette.
    pub ip: Vec<String>,
}

/// added 03.10.2026, TLS. **DIE VERBINDUNG ALS ANGABE** — das, was das Schloss
/// im Adressfeld zeigt.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct VerbindungsInfo {
    /// Der geprueffte Hostname, **ohne** Port.
    pub host: String,
    /// added 03.10.2026, TLS. **DIE VERSION ALS TEXT**, und der Grund fuer
    /// zwei feste Werte statt der Zahl: eine Zahl (`772`) liest sich in einem
    /// Dialog wie ein Messwert. RFC 8446 4.2.1 nennt `0x0304` „TLS 1.3“ und
    /// 4.1.2 `0x0303` „TLS 1.2“.
    pub version: &'static str,
    /// added 03.10.2026, TLS. **DIE ALPN-KENNUNG ALS TEXT** — `h2` oder
    /// `http/1.1`. `None`, wenn der Server keine geschickt hat (RFC 7301 3.2
    /// sagt dann HTTP/1.1) **oder** wenn die Kennung kein druckbarer ASCII-Text
    /// ist. Diese beiden Faelle sind fuer die Anzeige gleich: es gibt nichts
    /// zu zeigen, und eine Steuerzeichenfolge anzuzeigen waere kein Text.
    pub alpn: Option<String>,
    /// added 03.10.2026, TLS. **DIE OCSP-STUFE**, woertlich aus
    /// `TlsVerbindung::ocsp_urteil`. Sie ist eine **Zeichenkette des Urteils**,
    /// keine enum — und das ist Absicht: die Stufen werden in `strom.rs` und
    /// `strom12.rs` **an zwei Stellen** erzeugt, und eine dritte Aufzaehlung
    /// hier waere eine dritte Wahrheit ueber dieselbe Sache.
    pub ocsp_stufe: &'static str,
    /// Der Grund zur Stufe, im Klartext.
    pub ocsp_grund: &'static str,
    /// Die Kette, **Blatt zuerst** — dieselbe Reihenfolge wie in
    /// `TlsVerbindung::kette()`, und `stelle` in jedem Eintrag sagt dieselbe
    /// Sache als Zahl.
    pub kette: Vec<ZertifikatInfo>,
}

/// added 03.10.2026, TLS. **DER TEXT EINES ZEITPUNKTS**, und die Form ist
/// festgelegt: **`JJJJ-MM-TT hh:mm:ss UTC`**.
///
/// **WARUM NICHT DIE FORM VON FIREFOX** („Oct 1, 2026 9:51:29 PM GMT“): sie
/// haengt an einer Locale und an einer Landessprache, und eine Anzeige, die
/// ihren Text von der Systemsprache abhaengig macht, ist in einem Test nicht
/// pruefbar. **Diese Form ist es** — und sie ist umkehrbar, denn [`von_text`]
/// liest sie wieder. Wer sie anders zeigen will, hat die Zahl daneben.
///
/// **UND NEGATIVE ZEITEN SIND ERREICHBAR**, weil `Gueltigkeit` `i64` ist: ein
/// Zertifikat mit `notBefore` vor 1970 (das gab es, siehe
/// `testdaten/crl`) wird hier nicht zu einem `None` und nicht zu einem
/// Panic, sondern zu einem **Text vor dem Jahr 0**.
///
/// **DER UMRECHNUNGSSCHRITT**, woertlich der Algorithmus aus
/// `chrono`/`Howard Hinnant` („civil_from_days“, public domain), und die
/// Invariante ist in `der_tag_ist_richtig` **gemessen**, nicht behauptet: fuer
/// `t = 0` ist `z = 0` und der Tag `1970-01-01`.
pub fn zeit_als_text(sekunden: i64) -> String {
    // added 03.10.2026, TLS: **DIE EINZIGE STELLE, DIE RECHNET.** Alle
    // anderen Felder nehmen `i64` und geben `i64` zurueck; wer zweimal
    // umrechnet, bekommt bei einem Wert zwischen zwei Sekunden verschiedene
    // Texte, und die Anzeige wuerde zappeln.
    let tage = sekunden.div_euclid(86_400);
    let rest = sekunden.rem_euclid(86_400);
    let (jahr, monat, tag) = zivil_aus_tagen(tage);
    format!(
        "{jahr:04}-{monat:02}-{tag:02} {:02}:{:02}:{:02} UTC",
        rest / 3600,
        (rest % 3600) / 60,
        rest % 60
    )
}

/// added 03.10.2026, TLS. **DER TEXT ZURUECK**, und das ist kein Komfort:
/// `zeit_als_text` ist der einzige Ort, der etwas **rundet** — und ein Text,
/// den niemand lesen kann, traegt keine Rechnung. Fuer den Test
/// `zeit_text_ist_umkehrbar` ist das die zweite Haelfte.
///
/// **UND EIN FEHLER STATT EINER LUGN:** ein Text, der nicht `JJJJ-MM-TT hh:mm:ss
/// UTC` ist, wird **nicht** geraten. `falsches Format -> None` ist die einzige
/// Antwort, die nicht still eine falsche Zahl liefert.
pub fn von_text(text: &str) -> Option<i64> {
    let (datum, uhrzeit) = text.split_once(' ')?;
    if !uhrzeit.ends_with(" UTC") {
        return None;
    }
    let mut d = datum.split('-');
    let jahr: i64 = d.next()?.parse().ok()?;
    let monat: i64 = d.next()?.parse().ok()?;
    let tag: i64 = d.next()?.parse().ok()?;
    if d.next().is_some() || !(1..=12).contains(&monat) || !(1..=31).contains(&tag) {
        return None;
    }
    let mut u = uhrzeit.trim_end_matches(" UTC").split(':');
    let stunde: i64 = u.next()?.parse().ok()?;
    let minute: i64 = u.next()?.parse().ok()?;
    let sekunde: i64 = u.next()?.parse().ok()?;
    if u.next().is_some() || !(0..24).contains(&stunde) || minute > 59 || sekunde > 59 {
        return None;
    }
    Some(tage_aus_zivil(jahr, monat, tag) * 86_400 + stunde * 3600 + minute * 60 + sekunde)
}

/// added 03.10.2026, TLS. **TAGE SEIT 1970-01-01 -> (Jahr, Monat, Tag)**.
/// Der Algorithmus rechnet in einem **400-Jahres-Zyklus** und braucht deshalb
/// keine Tabelle und keine Schleife ueber Jahre — das ist der Grund, warum das
/// hier drei Zeilen sind und keine Liste mit 400 Eintraege.
///
/// **UND DER MONAT BEGINNT BEI 1**, nicht bei 0 wie im Algorithmus: die
/// Umrechnung `tag0 = zivil - 719468` laeuft sonst um einen Tag daneben, und
/// ein um einen Tag verschobenes Ablaufdatum ist der Fehler, den niemand
/// sieht, weil das Datum „fast“ stimmt.
fn zivil_aus_tagen(tage: i64) -> (i64, i64, i64) {
    let z = tage + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z.rem_euclid(146_097);
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let jahr = yoe + era * 400;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let tag = doy - (153 * mp + 2) / 5 + 1;
    let monat = if mp < 10 { mp + 3 } else { mp - 9 };
    // `mp >= 10` heisst Januar oder Februar des **naechsten** Jahres.
    (if monat <= 2 { jahr + 1 } else { jahr }, monat, tag)
}

/// added 03.10.2026, TLS. **Das Umgekehrte** von [`zivil_aus_tagen`], und es
/// ist eine eigene Funktion, weil die Umkehrung **nicht** dieselbe Formel ist:
/// `zivil_aus_tagen` rechnet mit einem 400-Jahres-Zyklus, und fuer die
/// Umkehrung braucht man die **Januarzahl** des Jahres (die Zahl der Tage bis
/// zum 1. Januar), nicht den Zyklus.
fn tage_aus_zivil(jahr: i64, monat: i64, tag: i64) -> i64 {
    let y = jahr - i64::from(monat <= 2);
    let era = y.div_euclid(400);
    let yoe = y - era * 400;
    // added 03.10.2026, TLS: **KEIN `as i64`** — die Parameter sind schon
    // `i64`, und der Umweg ueber `usize` (den clippy hier als
    // „casting to the same type“ meldete) waere eine Kopie ohne Zweck.
    let m = monat;
    let d = tag;
    let mp = if m > 2 { m - 3 } else { m + 9 };
    let doy = (153 * mp + 2) / 5 + d - 1;
    let doe = yoe * 365 + yoe / 4 - yoe / 100 + doy;
    era * 146_097 + doe - 719_468
}

/// added 03.10.2026, TLS. **DIE OID DER TLS-VERSION ALS TEXT**, und es ist
/// eine `match` ueber genau die **zwei** Werte, die `TlsVerbindung` liefern
/// kann. `VERSION_TLS12` ist **kein** Fall fuer sich: eine TLS-1.0-Verbindung
/// gibt es nicht (`ueber_sockel` bietet 1.3 und 1.2 an), und ein Text, den man
/// fuer einen Wert erhaelt, den es nicht gibt, waere eine erfundene Auskunft.
pub fn version_text(version: u16) -> &'static str {
    match version {
        crate::nachricht::VERSION_TLS13 => "TLS 1.3",
        crate::nachricht::VERSION_LEGACY => "TLS 1.2",
        _ => "unbekannte TLS-Version",
    }
}

/// added 03.10.2026, TLS. **EINE IP-ADRESSE ALS TEXT**, und zwar **nur** fuer
/// die beiden Formen, die RFC 5280 4.2.1.6 ueberhaupt zulaesst: 4 Byte
/// (IPv4) und 16 Byte (IPv6).
///
/// **WARUM NICHT `format!("{:?}")` oder `Ipv4Addr`/`Ipv6Addr`:** `std::net`
/// **hat** diese Typen, aber sie sind an IPv4/IPv6 gebunden und ihre
/// `Display` macht aus einer IPv6-Adresse `::ffff:192.0.2.1` (die
/// **IPv4-eingebettete** Form, RFC 4291 2.5.5.2). Ein Zertifikat, das
/// `::ffff:192.0.2.1` traegt, zeigt dann eine Adresse, die der Nutzer nie
/// getippt hat — und `traegt_ip` vergleicht **Bytes**, also waere die
/// Anzeigeadresse eine **andere** Behauptung als die geprueffte.
///
/// **UND EINE ANDERE LAENGE IST KEIN FEHLER, sondern eine unbekannte Form:**
/// RFC 5280 4.2.1.6 erlaubt fuer `iPAddress` genau 4 oder 16 Byte. Ein
/// Eintrag mit 5 Byte **darf** nicht vorkommen; wenn er doch vorkommt, ist das
/// eine Aussage ueber das Zertifikat und **kein** Absturz.
pub fn ip_als_text(bytes: &[u8]) -> Option<String> {
    match bytes.len() {
        4 => Some(format!(
            "{}.{}.{}.{}",
            bytes[0], bytes[1], bytes[2], bytes[3]
        )),
        16 => {
            let mut teile = [0u16; 8];
            for (i, t) in teile.iter_mut().enumerate() {
                *t = u16::from_be_bytes([bytes[2 * i], bytes[2 * i + 1]]);
            }
            // RFC 4291 2.2: die **laengste** Folge von Nullen wird zu `::`
            // zusammengezogen, und bei zwei gleichen Folgen die **erste**.
            let (mut start, mut laenge) = (usize::MAX, 0usize);
            let (mut i, mut lauf) = (0usize, 0usize);
            while i < 8 {
                if teile[i] == 0 {
                    lauf += 1;
                    if lauf > laenge {
                        start = i + 1 - lauf;
                        laenge = lauf;
                    }
                } else {
                    lauf = 0;
                }
                i += 1;
            }
            // added 03.10.2026, TLS: **LAENGE 1 WIRD NICHT ZUSAMMENGEZOGT.** RFC
            // 4291 2.2 verlangt fuer `::` **mindestens zwei** Nullgruppen
            // („at least one 16-bit 0 field“ gilt fuer die Schreibweise, aber
            // `1:0:2:3:4:5:6:7` schreibt man nicht als `1::7` — die Form
            // unterscheidet sich von `1:0:2:3:4:5:6:7` **nicht** und ist
            // deshalb **mehrdeutig**). Ohne diese Zeile waere
            // `1:0:2:3:4:5:6:7` als `1::2:3:4:5:6:7` lesbar — und das waere
            // eine **andere** Adresse, die der Nutzer fuer seine eigene haelt.
            if laenge < 2 {
                start = usize::MAX;
                laenge = 0;
            }
            let mut raus = String::new();
            let mut i = 0usize;
            while i < 8 {
                if i == start {
                    raus.push_str("::");
                    i += laenge;
                    continue;
                }
                if !raus.is_empty() && !raus.ends_with(':') {
                    raus.push(':');
                }
                raus.push_str(&format!("{:x}", teile[i]));
                i += 1;
            }
            // added 03.10.2026, TLS: **ALLES NULL.** Dann ist `start = 0`
            // und die Schleife sprang ueber alle acht Gruppen, also ist `raus`
            // `::` — das ist richtig. Fuer acht einzelne Nullen **ohne**
            // Zusammenziehen waere es `0:0:0:0:0:0:0:0`, und das wird hier
            // **nicht** erreicht, weil `laenge = 8 >= 2`. Beide Formen sind
            // gueltig; die kurze ist die, die der Nutzer kennt.
            Some(raus)
        }
        _ => None,
    }
}

/// added 03.10.2026, TLS. **EIN ZERTIFIKAT ALS ANGABE**, und das ist die
/// einzige Stelle, die aus [`Zertifikat`] eine [`ZertifikatInfo`] macht.
///
/// **DER `jetzt`-PARAMETER**, und nicht `SystemTime`: dieselbe Begruendung wie
/// bei `kette_pruefen` — ein Test muss ein Datum setzen koennen, und ein
/// Zertifikat, dessen `notAfter` in der Vergangenheit liegt, **darf** hier
/// herauskommen. Ein Feld, das die Entscheidung versteckt, ist keiner.
pub fn zertifikat_info(z: &Zertifikat, stelle: usize, jetzt: i64) -> ZertifikatInfo {
    let (schluessel_alg, schluessel_bit, kurve) = match &z.schluessel {
        SchluesselArt::Rsa { n, .. } => {
            // added 03.10.2026, TLS. **`(n.len() - fuehrende_null) * 8` — und
            // die fuehrende Null MUSS man abziehen.** Das war ein **echter
            // Fehler**, den der Test `rsa_bitzahl_ist_moduluslaenge_mal_acht`
            // gemessen hat: `n.len() * 8` lieferte **4104** fuer einen
            // 4096-Bit-Schluessel, weil der Modulus ein INTEGER mit **positivem
            // Hochbit** ist und DER dafuer ein fuehrendes `0x00` schreibt
            // (X.690 8.3.2: das erste Oktett eines positiven INTEGER ist nie
            // `0x00`, wenn das zweite Oktett `>= 0x80` beginnt).
            //
            // **UND DER WEG, DIE NULL ZU ERKENNEN, ist nicht „die erste“:**
            // `der::integer_als_bytes` **behaelt** sie (dort wird sie nur
            // *verworfen*, wenn sie **redundant** waere — also wenn das
            // zweite Oktett unter `0x80` beginnt). Eine vorhandene `0x00` ist
            // deshalb **immer** genau die eine, die abzuziehen ist. (Der
            // Kommentar in `crl.rs` sagt an anderer Stelle, `integer_als_bytes`
            // entferne eine fuehrende Null — **das ist nicht der Fall**, und
            // die Verifikation in `tests/zertifikatsinfo.rs` ist der Grund,
            // warum es hier auffaellt.)
            let ueber = n.first() == Some(&0x00);
            ("RSA", Some((n.len() - usize::from(ueber)) * 8), None)
        }
        SchluesselArt::Ecdsa { kurve: k, x, .. } => (
            "EC",
            // added 03.10.2026, TLS. **`x.len() * 8` UND NICHT DIE KURVE.**
            // Das war ein **echter Fehler**, gemessen von
            // `die_ganze_angabe_steht_am_echten_zertifikat`: mit der Kurven-OID
            // gerechnet kam **28** statt 256 heraus — `[1,2,840,10045,3,1,7]`
            // hat sieben Komponenten, und `7 * 4 = 28`. Die Bitzahl einer
            // Kurve steht in `x509::kurven_bits`, aber die **Anzeige** soll die
            // Laenge des Koordinatenfeldes nehmen: sie stimmt auch fuer eine
            // Kurve, die `kurven_bits` nicht kennt (`secp256k1`), und dann zeigt
            // die Anzeige keine erfundene Zahl.
            //
            // **UND GEMESSEN, dass `x.len() * 8` stimmt:** `openssl x509 -text`
            // gibt fuer P-256 `Public-Key: (256 bit)` und der Punkt hat
            // `04 || X (32) || Y (32)`, also `x = 32` Byte.
            Some(x.len() * 8),
            Some(x509::kurve_name(k)),
        ),
        SchluesselArt::Unbekannt { .. } => ("unbekannt", None, None),
    };
    ZertifikatInfo {
        stelle,
        ist_blatt: stelle == 0,
        inhaber: x509::name_als_text(&z.inhaber),
        aussteller: x509::name_als_text(&z.aussteller),
        seriennummer: crate::sha2::hexen(&z.seriennummer).to_uppercase(),
        gueltig_von: z.gueltigkeit.von,
        gueltig_bis: z.gueltigkeit.bis,
        gueltig_von_text: zeit_als_text(z.gueltigkeit.von),
        gueltig_bis_text: zeit_als_text(z.gueltigkeit.bis),
        gueltig: z.gueltigkeit.enthaelt(jetzt),
        ist_ca: z
            .basic_constraints
            .as_ref()
            .map(|b| b.ist_ca)
            .unwrap_or(false),
        schluessel_alg,
        schluessel_bit,
        kurve,
        signatur: x509::signatur_name(&z.signatur_algorithmus.oid),
        namen: z.san.as_ref().map(|s| s.dns.clone()).unwrap_or_default(),
        email: z
            .san
            .as_ref()
            .map(|s| {
                s.email
                    .iter()
                    .filter_map(|e| String::from_utf8(e.clone()).ok())
                    .collect()
            })
            .unwrap_or_default(),
        // added 03.10.2026, TLS: **`filter_map`, nicht `map`.** Ein
        // `iPAddress`-Eintrag mit anderer Laenge als 4 oder 16 kommt in keinem
        // RFC-5280-Zertifikat vor; **wenn** er vorkommt, ist die Zeile in der
        // Anzeige die falsche, also weggelassen. `map` wuerde `None` in eine
        // leere Zeile und damit **eine Adresse zeigen, die es nicht gibt**.
        ip: z
            .san
            .as_ref()
            .map(|s| s.ip.iter().filter_map(|b| ip_als_text(b)).collect())
            .unwrap_or_default(),
    }
}

/// added 03.10.2026, TLS. **DIE GANZE VERBINDUNG ALS ANGABE**.
///
/// **DIE PARAMETER SIND DIE, DIE `TlsVerbindung` ANBIETET** — und das ist der
/// Grund fuer diese Signatur und gegen eine, die `&TlsVerbindung` nimmt: der
/// Aufrufer hat den Strom **hinter** `Box<dyn Leitung>` im `pool.rs`
/// (`narsil-net`, fremde Datei) und kann dort weder entnehmen noch downcasten.
/// Wer die Info nur mit dem Stream bauen kann, baut sie gar nicht — und genau
/// daran ist ein Feature schon einmal gescheitert (die Nachschrift, siehe
/// `TlsVerbindung::nachschrift`).
///
/// **`kette_der` ist `&[Vec<u8>]`**, weil `TlsVerbindung::kette()` genau das
/// zurueckgibt. Jedes Glied wird mit dem **oeffentlichen**
/// `x509::zertifikat_lesen` gelesen — derselbe Weg, den der Handshake nahm, und
/// damit **keine** zweite Lesart.
///
/// **DER FEHLER IST BEKANNT UND BENANNT**, und nicht verschluckt: ein
/// unlesbares Zertifikat **in der Mitte** der Kette waere eine Anzeige, in der
/// eine Zeile fehlt, ohne dass erkennbar waare, **welche**. Also
/// `ZertifikatUnlesbar` mit dem Index, und der Dialog kann sagen „Zertifikat 2
/// ist unlesbar“ statt „Verbindung gesichert“.
/// **UND DIE STUFEN SIND `&'static str`, nicht `String`.** Sie stammen aus
/// `TlsVerbindung::ocsp_urteil()`, das `(&'static str, &'static str)`
/// zurueckgibt — die Stufen sind in `strom.rs` und `strom12.rs` an **zwei**
/// Stellen als Konstanten geschrieben, und sie hier zu `String` zu machen,
/// wuerde eine Kopie einer Sache sein, die es genau zweimal gibt.
pub fn verbindungsinfo(
    host: &str,
    version: u16,
    alpn: Option<&[u8]>,
    ocsp: (&'static str, &'static str),
    kette_der: &[Vec<u8>],
    jetzt: i64,
) -> Result<VerbindungsInfo, InfoFehler> {
    if kette_der.is_empty() {
        return Err(InfoFehler::KetteLeer);
    }
    let mut kette: Vec<ZertifikatInfo> = Vec::with_capacity(kette_der.len());
    for (stelle, der) in kette_der.iter().enumerate() {
        // added 03.10.2026, TLS: **`stelle` GEHT IN DEN FEHLER**, weil die
        // Anzeige ueber `stelle`/`ist_blatt` spricht. Der Text von
        // `X509Fehler` wird benannt statt weggeworfen — ein `unwrap` waere hier
        // ein Absturz mitten im Aufbau einer Anzeige, und ein `map_err` ohne
        // Ort wuerde „Zertifikat unlesbar“ sagen, ohne **welches**.
        let z = x509::zertifikat_lesen(der).map_err(|e| InfoFehler::ZertifikatUnlesbar {
            stelle,
            grund: e.to_string(),
        })?;
        kette.push(zertifikat_info(&z, stelle, jetzt));
    }
    Ok(VerbindungsInfo {
        host: host.to_string(),
        version: version_text(version),
        // added 03.10.2026, TLS: **`from_utf8` UND PRUEFUNG AUF DRUCKBAR.**
        // `String::from_utf8` allein liefert `Some` fuer `\0` und `\n` — und
        // eine ALPN-Kennung mit einem Zeilenumbruch in einem Dialog ist eine
        // Injection in die Anzeige. RFC 7301 3.1 sagt fuer `ProtocolName`
        // `opaque <1..2^8-1>`, also **beliebig**: die Pruefung gehoert hierher
        // und nicht in den Handshake, weil der Handshake die Kennung zum
        // Protokollvergleich braucht und **nicht** zum Anzeigen.
        alpn: alpn.and_then(|a| {
            std::str::from_utf8(a)
                .ok()
                .filter(|s| !s.is_empty() && s.bytes().all(|b| (0x21..=0x7e).contains(&b)))
                .map(String::from)
        }),
        ocsp_stufe: ocsp.0,
        ocsp_grund: ocsp.1,
        kette,
    })
}

