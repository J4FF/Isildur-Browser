/// added 03.10.2026, Rolle TLS (Auftrag: nutzersichtbare Sicherheit).
/// **DIE KATEGORIE DER WARNUNG**, und sie ist **kein Urteil ueber eine
/// gueltige Verbindung**, sondern die **Benennung eines Fehlers, der die
/// Verbindung verhindert hat**.
///
/// **UND DAS IST DER PUNKT, an dem der Dateikopf seemingly widersprochen wird:**
/// oben steht, diese Datei liefere **kein** „sicher/unsicher". Das stimmt und
/// gilt hier **nicht**: eine Warnseite erscheint **nur**, wenn die Verbindung
/// **scheiterte**. Sie ersetzt keine Anzeige, sie verhindert eine — und Firefox
/// macht genau das. **Der Unterschied ist derselbe wie bei einer 404-Seite:**
/// die 404 sagt nicht „diese Seite ist schlecht", sie sagt „hier ist nichts".
///
/// **DIE DREI KATEGORIEN SIND DIE VON FIREFOX**, und sie sind **nicht** von mir
/// erfunden: Firefox zeigt „This site is not secure“ und nennt danach den
/// Grund — abgelaufen, der Name passt nicht, oder die Ausstellerin ist
/// unbekannt. **GEMESSEN, woher die Zuordnung kommt:** aus den Varianten von
/// `KetteFehler`, nicht aus einer Zeichenkette. `KeinAussteller` heisst
/// „die Ausstellerin steht nicht im Vertrauensspeicher" — das ist **auch**
/// der Fall bei einem selbstsignierten Zertifikat, und ich trenne die beiden
/// **nicht**, weil die Daten sie nicht trennen: `KetteFehler` sagt
/// „keine Ausstellerin gefunden", nicht „selbstsigniert".
// added 04.10.2026, TLS: **`Copy` dazu**, und der Grund ist
// `error[E0382]: use of moved value 'art'` an der Text-Bruecke. `WarnArt` hat
// **keine** Felder, also ist `Copy` korrekt und **kostet nichts** — und es
// macht `zertifikatswarnung` und `zertifikatswarnung_aus_text` vergleichbar,
// ohne dass eine Variante umzieht.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum WarnArt {
    /// `AusserhalbDerGueltigkeit` mit `jetzt > bis`: **abgelaufen**.
    Abgelaufen,
    /// `AusserhalbDerGueltigkeit` mit `jetzt < von`: **noch nicht gueltig**.
    NochNichtGueltig,
    /// `HostnamePasstNicht`: das Zertifikat gilt fuer einen **anderen** Namen.
    FalscherHost,
    /// `KeinAussteller`, `SignaturPasstNicht`: die Ausstellerin ist unbekannt
    /// oder ihre Signatur passt nicht. **Enthaelt den selbstsignierten Fall.**
    UnbekannteAusstellerin,
    /// `ZuTief`, `HashNichtUnterstuetzt`, `ZertifikatUngueltig`: die Kette
    /// selbst ist kaputt. Firefox nennt das „unbekanntes Format".
    KetteKaputt,
    /// Alles andere.
    Sonstiges,
}

/// added 03.10.2026, Rolle TLS. **DIE WARNSEITE ALS DATEN**, und als Daten
/// aus **drei** Gruenden gegen einer fertigen Zeichenkette:
///
/// 1. **Der Dialog braucht die Felder einzeln** — Firefox hebt das Ablaufdatum
///    hervor, den falschen Host aber nur als Nebensatz.
/// 2. **Die Oberflaeche entscheidet die Laenge.** `narsil-chrome` zeichnet, und
///    eine Zeile, die dort gebaut wird, kann dort nicht umgebrochen werden.
/// 3. **Testbar ohne Browser.** Genau wie [`zertifikat_info`] ist das hier eine
///    reine Funktion ueber einen Fehler — kein Netz, keine Uhr, kein Fenster.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Zertifikatswarnung {
    /// Die Kategorie, an der die Oberflaeche den Text waehlt.
    pub art: WarnArt,
    /// Der Host, um den es geht — fuer die Anzeige, nicht fuer die Pruefung.
    pub host: String,
    /// Ein Satz, der den Grund **fuer den Benutzer** sagt. Fest, weil Firefox
    /// ihn auch fest hat.
    pub erklaerung: &'static str,
    /// Der technische Fehler **woertlich** — fuer den „Technische Details"
    /// aufklappbereich, und unveraendert, weil dort keine Zusammenfassung
    /// sondern die Tatsache gehoert.
    pub technisch: String,
    /// added 04.10.2026, TLS: **DER AUSSTELLER**, als Text, oder **leer**, wenn
    /// das Zertifikat nicht mitgegeben wurde.
    ///
    /// **WARUM EIN ZUSATZFELD, und nicht ein Text im `technisch`:** die Seite
    /// soll den Aussteller **lesbar** zeigen („R3, O=Let's Encrypt, CN=R3“), und
    /// `Name` ist ein **Baum**, kein String. Die Umrechnung gehoert an **eine**
    /// Stelle — hier.
    pub aussteller: String,
    /// added 04.10.2026, TLS: **DIE ZEITEN LESBAR**, nicht als Unix-Zahl.
    ///
    /// **GEMESSEN, warum das keine Kosmetik ist:** der Aufklappbereich zeigte
    /// `1578836800 .. 1580515200, geprueft bei 1580515260`. Der Benutzer kann
    /// daraus **nichts** ablesen. `zeit_als_text` macht daraus
    /// „2020-01-01 00:00:00 UTC“ — und das ist **dieselbe** Funktion wie im
    /// Schloss, also **eine** Zeitdarstellung im ganzen Browser.
    pub von: String,
    /// `notAfter` als Text.
    pub bis: String,
    /// Der Pruefzeitpunkt als Text.
    pub geprueft: String,
}

/// added 03.10.2026, Rolle TLS. **DIE WARNUNG AUS EINEM FEHLER BAUEN**, und die
/// Zuordnung ist **je Variante eine Zeile** — sie ist der ganze Inhalt dieser
/// Funktion.
///
/// **UND `zeit_als_text` WIRD WIEDERVERWENDET**, nicht neu erfunden: die
/// Datumsangaben in der Erklaerung kommen aus derselben Funktion, die schon
/// im Schloss steht. **Zwei** Datumsformate fuer **ein** Datum waere eine
/// zweite Wahrheit.
///
/// **UND WAS DIESE FUNKTION NICHT KANN:** sagen, ob der Benutzer dem
/// Zertifikat trauen soll. Das ist eine **Benutzer**entscheidung, und eine
/// Warnseite, die sie vorwegnimmt, waere wieder ein Urteil. Sie liefert den
/// Grund und sonst nichts.
pub fn zertifikatswarnung(fehler: &KetteFehler, host: &str) -> Zertifikatswarnung {
    let technisch = fehler.to_string();
    let art = match fehler {
        // added 03.10.2026, TLS: **DIE ZWEI RICHTUNGEN DER GELTIGKEIT.** Der
        // Fehler nennt `von`, `bis` und `jetzt`, also ist die Richtung
        // **entscheidbar** — und „abgelaufen“ und „noch nicht gueltig“ sind
        // **verschiedene** Ratschlaege fuer den Benutzer.
        KetteFehler::AusserhalbDerGueltigkeit { von, bis, jetzt } => {
            if *jetzt >= *bis {
                WarnArt::Abgelaufen
            } else if *jetzt < *von {
                WarnArt::NochNichtGueltig
            } else {
                WarnArt::KetteKaputt
            }
        }
        KetteFehler::HostnamePasstNicht => WarnArt::FalscherHost,
        KetteFehler::KeinAussteller | KetteFehler::SignaturPasstNicht { .. } => {
            WarnArt::UnbekannteAusstellerin
        }
        KetteFehler::ZuTief { .. }
        | KetteFehler::HashNichtUnterstuetzt
        | KetteFehler::ZertifikatUngueltig { .. } => WarnArt::KetteKaputt,
        _ => WarnArt::Sonstiges,
    };
    // added 04.10.2026, TLS: **`erklaerung_fuer(art)` statt eines zweiten
    // `match`** — es gab zwei Texttabellen an zwei Stellen, und genau das ist
    // die Sorte Fehler, die man erst beim Lesen findet. Jetzt gibt es **eine**.
    // added 04.10.2026, TLS: **DIE ZEITEN AUCH HIER, und nicht erst in**
    // `zertifikatswarnung_mit_zertifikat` — **GEMESSEN, warum:** der Test
    // `die_zeiten_stehen_als_datum_und_zeit_da` rief `zertifikatswarnung` und
    // bekam **leere** Felder (`left: ""`). Die drei Zahlen stehen im
    // **Fehler**, nicht im Zertifikat — also gehoeren sie hierher, und die
    // Variante mit Zertifikat **ergaenzt** nur den Aussteller.
    let (von, bis, geprueft) = match fehler {
        KetteFehler::AusserhalbDerGueltigkeit { von, bis, jetzt } => (
            zeit_als_text(*von),
            zeit_als_text(*bis),
            zeit_als_text(*jetzt),
        ),
        _ => (String::new(), String::new(), String::new()),
    };
    Zertifikatswarnung {
        art,
        host: host.to_string(),
        // Translated when the warning is made (the page shows it as is).
        erklaerung: narsil_i18n::tr(erklaerung_fuer(art)),
        technisch,
        aussteller: String::new(),
        von,
        bis,
        geprueft,
    }
}

/// added 04.10.2026, TLS: **DIE WARNUNG MIT ZERTIFIKAT**, und das ist die
/// Form, in der die Seite sie braucht: mit **Aussteller** und **lesbaren
/// Zeiten**. `zertifikatswarnung` bleibt fuer die Aufrufer, die nur die
/// Kategorie wollen.
///
/// **UND DIE ZEITEN KOMMEN AUS DEM FEHLER, nicht aus dem Zertifikat:** der
/// Fehler nennt `von`, `bis` und `jetzt` **selbst** — und genau die drei, um die
/// es geht. Das Zertifikat waere die zweite Quelle fuer dieselben Zahlen.
pub fn zertifikatswarnung_mit_zertifikat(
    fehler: &KetteFehler,
    host: &str,
    blatt: Option<&Zertifikat>,
) -> Zertifikatswarnung {
    // added 04.10.2026, TLS: **NUR NOCH DER AUSSTELLER** — die Zeiten kommen aus
    // `zertifikatswarnung`, sonst waeren sie an **zwei** Stellen berechnet.
    let mut w = zertifikatswarnung(fehler, host);
    if let Some(z) = blatt {
        w.aussteller = crate::x509::name_als_text(&z.aussteller);
    }
    w
}

