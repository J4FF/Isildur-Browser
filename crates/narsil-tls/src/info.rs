    #[test]
    fn die_zeiten_stehen_als_datum_und_zeit_da() {
        let _de = narsil_i18n::scoped(narsil_i18n::Language::German); // the German wording of the page
        // added 04.10.2026, TLS: **DIE ZAHLEN SIND KONTROLLIERT**, und der Weg
        // dorthin ist die eigentliche Lehre: ich hatte `1_578_836_800` statt
        // `1_577_836_800` geschrieben — **838** gegen **383**. Das sind rund
        // 1 000 000 Sekunden, also **11,6 Tage**, und `zeit_als_text` gab
        // deshalb zu Recht „2020-01-12 13:46:40 UTC“ statt „2020-01-01“. **Ich
        // war im Begriff, daraus einen Bug in `zeit_als_text` zu melden.**
        //
        // **GEMACHT HABE ICH ES NICHT, weil ich die Zahl nachgerechnet habe**
        // (`datetime.utcfromtimestamp`, unabhaengig von Rust). **Eine
        // ungeprueffte Vermutung, dass der Code falsch ist, ist so ein Fund wie
        // ein echter Fehler** — und der Unterschied ist eine Minute Rechnen.
        let fehler = KetteFehler::AusserhalbDerGueltigkeit {
            von: 1_577_836_800,
            bis: 1_580_515_200,
            jetzt: 1_580_515_260,
        };
        let w = zertifikatswarnung(&fehler, "expired.test");
        assert_eq!(w.von, "2020-01-01 00:00:00 UTC", "nicht als Unix-Zahl");
        // added 04.10.2026, TLS: **`bis` IST DER 1. FEBRUAR, nicht der 1. Januar**
        // — nachgerechnet. Ein Zertifikat, das am 1. Januar 2020 00:00:00 began
        // und am 1. Februar endet, hat **31 Tage**. Ich hatte „2020-01-“
        // erwartet und damit meinen **eigenen** Testwert bemerkt.
        assert!(w.bis.starts_with("2020-02-01"), "{}", w.bis);
        assert!(w.geprueft.starts_with("2020-02-01"), "{}", w.geprueft);
        let html = warnseite_html(&w);
        assert!(
            html.contains("2020-01-01 00:00:00 UTC"),
            "im Aufklappbereich"
        );
        // added 04.10.2026, TLS: **DIE LESBAREN ZEILEN SIND EIGENE ZEILEN**, mit
        // eigenem Namen — das ist die eigentliche Forderung. **UND die
        // Unix-Zahlen bleiben im woertlichen Text**, und **das ist Absicht**:
        // `technisch` gibt die Zeile wieder, **wie der Code sie meldete**, und
        // ein Fehlerbericht mit Originalzahlen ist beim Nachsehen mehr wert als
        // einer mit einer Umrechnung, der man nicht traut. Firefox zeigt beides.
        //
        // **MEINE ERSTE ZUSICHERUNG WAR FALSCH** (`!html.contains(...)`) und
        // wurde rot: `w.technisch` enthaelt die Zahlen **absichtlich**.
        for name in ["Gültig von", "Gültig bis", "Geprüft am"] {
            assert!(html.contains(name), "die Zeile {name} fehlt");
        }
        assert!(
            html.contains("Technische Angabe"),
            "und der woertliche Text bleibt fuer den Fehlerbericht"
        );
        // added 04.10.2026, TLS: **UND DIE LEEREN ZEILEN FEHLEN**, sonst stuende
        // da ein „Aussteller:“ ohne Wert.
        assert!(
            !html.contains("Aussteller"),
            "ohne Zertifikat kein Aussteller"
        );
    }

    /// added 04.10.2026, TLS: **DER AUSSTELLER**, und er kommt aus **einem**
    /// `Name`-Baum — der Grund fuer `x509::name_als_text` statt `to_string`.
    #[test]
    fn der_aussteller_kommt_in_rfc4514_form() {
        // added 04.10.2026, TLS: **`bauen::zertifikat()` LIEFERT `Vec<u8>`**
        // (DER), nicht `Zertifikat` — GEMESSEN am Compilerfehler „expected
        // `&Zertifikat`, found `&Vec<u8>`“. Das Lesen gehoert also dazu.
        let der = crate::x509::bauen::zertifikat(true).unwrap_or_else(|_| panic!("Blatt"));
        let z = x509::zertifikat_lesen(&der).unwrap_or_else(|_| panic!("Blatt lesen"));
        let w = zertifikatswarnung_mit_zertifikat(
            &KetteFehler::KeinAussteller,
            "self-signed.test",
            Some(&z),
        );
        assert!(!w.aussteller.is_empty(), "der Aussteller ist gesetzt");
        assert_eq!(w.aussteller, x509::name_als_text(&z.aussteller));
        let html = warnseite_html(&w);
        assert!(html.contains("Aussteller"), "im Aufklappbereich");
        assert!(
            html.contains(&html_escapen(&w.aussteller)),
            "und mit dem Text"
        );
    }

    /// added 04.10.2026, TLS: **DIE UEBERSCHRIFT IST DREIMAL DASSELBE** — Titel,
    /// `<h1>` und der Firefox-Text. Wer einen davon aendert, hat eine Seite, in
    /// der die Fenstertitel und der Inhalt **verschieden** sind.
    #[test]
    fn titel_und_ueberschrift_sagen_dasselbe() {
        let _de = narsil_i18n::scoped(narsil_i18n::Language::German); // the German wording of the page
        let w = zertifikatswarnung(&KetteFehler::KeinAussteller, "x.test");
        let html = warnseite_html(&w);
        assert!(html.contains("<title>Warnung: Mögliches Sicherheitsrisiko</title>"));
        assert!(html.contains("<h1>Warnung: Mögliches Sicherheitsrisiko</h1>"));
        // added 03.10.2026, TLS: **UND DIE SEITE IST VOLLSTAENDIG** — mit
        // `DOCTYPE` und `charset`, weil ein Browser ohne Charset
        // Umlaute als Ersatzzeichen anzeigt.
        assert!(html.starts_with("<!DOCTYPE html>"), "DOCTYPE fehlt");
        assert!(html.contains("charset=\"utf-8\""), "charset fehlt");
    }
