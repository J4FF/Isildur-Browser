/// added 03.10.2026, TLS. **DAS MASKIEREN**, und es ist **eine** Funktion aus
/// **drei** Ersetzungen — die Reihenfolge ist nicht beliebig.
///
/// **UND WARUM ES HIER NOTWENDIG IST, obwohl der Host aus dem Netz kommt:**
/// Der Fehlertext und der Host landen in einer **HTML-Seite**. Ohne Maskieren
/// waere ein Host wie `a"><script>` ein **Skript in der Warnseite** — und die
/// Warnseite ist genau die Seite, auf der der Benutzer **klicken soll**. Das
/// waere keine theoretische Luecke, sondern ein Angriff ueber die
/// Fehlermeldung.
///
/// **UND `&` ZUERST**, sonst wuerde das `&amp;` aus der zweiten Ersetzung
/// **noch einmal** maskiert und der Text zeigte `&amp;lt;`. GEMESSEN als
/// Reihenfolgeproblem beim Schreiben, nicht geraten.
fn html_escapen(text: &str) -> String {
    text.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}

/// added 04.10.2026, TLS: **DIE BRUECKE UEBER DEN TEXT**, und sie ist
/// **ersatzweise** gebaut und **so benannt**.
///
/// **WARUM SIE NOETIG IST, und das ist gemessen:** `narsil_net::NetError` hat
/// **keine** Variante fuer einen Kettenfehler. GEMESSEN an
/// `crates/narsil-net/src/lib.rs`: die Kettenpruefung laeuft ueber
/// `.map_err(|e| NetError::Tls(e.to_string()))` (Zeile 2389), und
/// `NetError::Tls(String)` ist die **einzige** TLS-Variante (Zeile 1338).
/// **DIE STRUKTUR GEHT AUF DEM WEG ZUR OBERFLAECHE VERLOREN** — in `narsil`
/// kommt nur **Text** an.
///
/// **UND DESHALB IST SIE ZWEITES, NICHT ERSTES:** [`zertifikatswarnung`] nimmt
/// die **Variante** und ist damit **immer richtig**; diese Funktion nimmt den
/// **Text** und ist damit **nur so gut wie die Formate von `Display`**. Der
/// Aufruf in `narsil/src/laden.rs` benutzt sie nur, weil `NetError::Kette` nicht
/// existiert — **BRETT 25:0x Punkt 6** nennt die eine fehlende Variante.
///
/// **DIE FORMATE SIND FESTGENAGELT, und zwar gegen `kette.rs`:** die
/// `Display`-Texte sind an Zeile 256 ff. abgeschrieben, **nicht** geraten, und
/// `zertifikatswarnung_aus_text_tests` vergleicht sie woertlich. **Wird
/// `Display` in `kette.rs` umformuliert, wird dieser Test rot** — das ist der
/// Zweck.
///
/// **UND `NetError::Tls` HAT DAS PRÄFIX „TLS: “**, woertlich `lib.rs:1465`.
/// Das wird abgeschnitten, sonst fände `contains` nichts.
pub fn zertifikatswarnung_aus_text(text: &str, host: &str) -> Zertifikatswarnung {
    use WarnArt::*;
    let t = text.strip_prefix("TLS: ").unwrap_or(text).trim();
    let art = if t.contains("ausserhalb der Gueltigkeit") {
        // added 04.10.2026, TLS: **ABGELAUFEN ODER NOCH NICHT GUELTIG** — der
        // Text traegt **beide** Zahlenpaare, und die Richtung liess sich daraus
        // nur mit einem zweiten Vergleich. **GEMESSEN, warum das ehrlicher
        // ist als Raten:** `ausserhalb der Gueltigkeit: 1577836800 ..
        // 1580515200, geprueft bei 1580515260` nennt `jetzt` **hinter** `bis`,
        // also abgelaufen. **UND WENN DIE ZAHLEN FEHLEN**, ist die Kategorie
        // `Sonstiges` — **nicht** `Abgelaufen`. Eine Warnseite, die „abgelaufen“
        // sagt, ohne es zu wissen, ist schlimmer als eine, die schweigt.
        let zahlen: Vec<i64> = t
            .split(|c: char| !c.is_ascii_digit())
            .filter(|s| !s.is_empty())
            .filter_map(|s| s.parse().ok())
            .collect();
        match (zahlen.first(), zahlen.get(1), zahlen.get(2)) {
            (Some(_), Some(&bis), Some(&jetzt)) if jetzt >= bis => Abgelaufen,
            (Some(&von), Some(_bis), Some(&jetzt)) if jetzt < von => NochNichtGueltig,
            _ => Sonstiges,
        }
    } else if t.contains("der Name traegt den Hostnamen nicht") {
        FalscherHost
    } else if t.contains("kein Aussteller gefunden") || t.contains("passt nicht") {
        UnbekannteAusstellerin
    } else if t.contains("Kette tiefer als")
        || t.contains("kein gueltiges X.509")
        || t.contains("Hash des Signaturalgorithmus unbekannt")
    {
        KetteKaputt
    } else {
        // added 04.10.2026, TLS: **`Sonstiges`, und das ist eine Entscheidung.**
        // Die Alternative waere, jeden unbekannten Text als „Kette kaputt“ zu
        // melden — dann behauptet die Seite einen Grund, den sie nicht hat.
        Sonstiges
    };
    Zertifikatswarnung {
        art,
        host: host.to_string(),
        // Translated when the warning is made (the page shows it as is).
        erklaerung: narsil_i18n::tr(erklaerung_fuer(art)),
        technisch: text.to_string(),
        aussteller: String::new(),
        // added 04.10.2026, TLS: **AUCH HIER DIE LESBAREN ZEITEN**, weil die
        // Bruecke sonst die **schlechteste** Anzeige lieferte — gerade die,
        // die der Benutzer braucht.
        von: zeit_als_text(zahlen_vom_text(t, 0)),
        bis: zeit_als_text(zahlen_vom_text(t, 1)),
        geprueft: zeit_als_text(zahlen_vom_text(t, 2)),
    }
}

/// added 04.10.2026, TLS: **DIE N-TE ZEITZAHL AUS EINEM FEHLERTEXT**, und sie
/// gibt **0** zurueck, wenn es keine gibt — der Aufrufer formt daraus den Text
/// und **leer** ist der Fall „nicht vorhanden“.
///
/// **UND WARUM EINE EIGENE FUNKTION:** der Gueltigkeitszweig braucht dieselben
/// drei Zahlen fuer die **Kategorie**, und fuer die **Anzeige** sind es dieselben
/// drei. **Zweimal geparst** waere eine zweite Wahrheit.
fn zahlen_vom_text(t: &str, n: usize) -> i64 {
    t.split(|c: char| !c.is_ascii_digit())
        .filter(|s| !s.is_empty())
        .filter_map(|s| s.parse::<i64>().ok())
        .nth(n)
        .unwrap_or(0)
}

/// added 04.10.2026, TLS: **DER TEXT JE KATEGORIE**, als **eine** Funktion —
/// weil `zertifikatswarnung` und `zertifikatswarnung_aus_text` **dieselben**
/// Woerter sagen muessen. **Zwei Texte an zwei Stellen** waere die Art von
/// Fehler, die man erst beim Lesen findet.
///
/// **UND SIE IST DARUM AUCH `pub`:** der Test braucht sie, und sie ist die
/// **eine** Quelle fuer beide Wege.
/// Returns an English translation key; the warning page shows it with `tr`.
pub fn erklaerung_fuer(art: WarnArt) -> &'static str {
    match art {
        WarnArt::Abgelaufen => {
            narsil_i18n::tr_key("The certificate of this site has expired. Someone could read the traffic.")
        }
        WarnArt::NochNichtGueltig => {
            narsil_i18n::tr_key("The certificate of this site is not valid yet — or the computer's clock is wrong.")
        }
        WarnArt::FalscherHost => {
            narsil_i18n::tr_key("The certificate is for a different name. You are opening a different site than the certificate says.")
        }
        WarnArt::UnbekannteAusstellerin => {
            narsil_i18n::tr_key("The issuer of this certificate is unknown or its signature does not match — that is exactly the case for a self-signed certificate.")
        }
        WarnArt::KetteKaputt => {
            narsil_i18n::tr_key("The certificate chain of this site is incomplete or damaged.")
        }
        WarnArt::Sonstiges => narsil_i18n::tr_key("The connection to this site could not be made securely."),
    }
}

