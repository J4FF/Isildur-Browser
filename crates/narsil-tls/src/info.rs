//! added 03.10.2026, Rolle TLS. **DIE ZERTIFIKATSINFO FUER DAS SCHLOSS IM
//! ADRESSFELD** — die Daten, keine Anzeige.
//!
//! -------------------------------------------------------------------------
//! WARUM DIES EINE EIGENE DATEI IST und nicht ein Feld an `Response`
//! -------------------------------------------------------------------------
//! `narsil-net` haengt an `narsil-tls`, **nicht** umgekehrt: `Response` liegt in
//! `narsil-net` und kann `narsil_tls::info` nicht nennen, ohne dass die Crate
//! umgedreht wird. Diese Datei ist deshalb **das Ende der Kette**, das die
//! Oberflaeche (`narsil-chrome`, `narsil`) aufruft — mit genau den Werten, die
//! `TlsVerbindung` anbietet. **Kein Umweg, keine zweite Wahrheit.**
//!
//! -------------------------------------------------------------------------
//! WAS HIER NICHT STEHT, und warum das eine Entscheidung ist
//! -------------------------------------------------------------------------
//! **KEIN „die Verbindung ist sicher“ / „unsicher“.** Das waere eine
//! **Bewertung**, und sie gehoert dem, der sie anzeigt: `narsil-chrome` zeichnet
//! das Schloss, und ein Urteil, das hier faellt, kann die Zeichnung nicht mehr
//! korrigieren. Diese Datei liefert die **Tatsachen** — gueltig ja/nein, OCSP
//! gut/fehlt/kaputt, Version, Kette — und **nichts** als Urteil darueber.
//!
//! **UND KEINE ZEICHENKETTE FUER DIE GANZE ANZEIGE.** Wer eine Zeile
//! zusammenbaut, kann sie nur an **einer** Stelle formatieren; ein Dialog, der
//! die Gueltigkeit hervorheben will, braucht aber die Felder einzeln. Also
//! Felder, und die Zeitangaben **zusaetzlich** als Text (siehe
//! [`zeit_als_text`]).
//!
//! -------------------------------------------------------------------------
//! DIE NORMEN, und jede Zeile hier hat eine
//! -------------------------------------------------------------------------
//! * **RFC 4514** — der Name als Text (`x509::name_als_text`). Woertlich 2.1:
//!   „the output is generated by **reversing** the order of the RDNs“.
//! * **RFC 5280** 4.1.2.5 — die Gueltigkeit, **einschliesslich** beider
//!   Grenzen: „valid during the period from notBefore through notAfter,
//!   **inclusive**“. Genau das macht `Gueltigkeit::enthaelt`, und diese Datei
//!   rechnet **nicht** selbst.
//! * **RFC 8446** 4.1 / 4.2.1 — die Version, und 4.2.2 die Kette „Blatt
//!   zuerst“ — die Reihenfolge, in der `kette_der` kommt.
//!
//! Nur `std`. Kein `unsafe`. Keine Fremd-Crates.

