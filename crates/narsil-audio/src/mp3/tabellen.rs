    #[test]
    fn die_aliastabelle_hat_acht_schritte_zu_zwei_werten() {
        // `csa_table[j][0]^2 + csa_table[j][1]^2 == 1` je Schritt — das
        // ist die Orthogonalitaet, und sie stimmt nur bis auf die
        // `float`-Genauigkeit der Quelle (etwa 5e-6).
        for j in 0..8usize {
            let s = ALIAS[j * 4] * ALIAS[j * 4] + ALIAS[j * 4 + 1] * ALIAS[j * 4 + 1];
            assert!(
                (s - 1.0).abs() < 1e-5,
                "Schritt {j}: a^2 + b^2 = {s}, nicht 1"
            );
            assert!(
                ALIAS[j * 4] > 0.0,
                "Schritt {j}: der erste Wert muss positiv sein"
            );
        }
    }

    /// Das Synthesefenster ist **mit Vorzeichenwechsel** gespiegelt.
    ///
    /// # GEMESSENER FEHLER: 252 VON 512 WERTEN FALSCH
    ///
    /// Ich hatte die Norm als „`D[j] = D[512-j]`" gelesen und ohne
    /// Vorzeichenwechsel gespiegelt; der Test pruefte genau das und hat
    /// den Fehler **festgeschrieben**. Der Wechsel ist belegt an
    /// `mpa_synth_init` in `libavcodec/mpegaudiodsp_template.c`.
    #[test]
    fn das_synthesefenster_ist_gespiegelt_mit_vorzeichenwechsel() {
        for i in 1..257usize {
            let soll = if (i & 63) != 0 {
                -SYNTHESE_FENSTER[i]
            } else {
                SYNTHESE_FENSTER[i]
            };
            assert_eq!(
                SYNTHESE_FENSTER[512 - i],
                soll,
                "D[{}] passt nicht zu D[{i}]: {} statt {soll}",
                512 - i,
                SYNTHESE_FENSTER[512 - i]
            );
        }
        assert_eq!(SYNTHESE_FENSTER[0], 0.0, "D[0] ist 0");
        assert!(
            (SYNTHESE_FENSTER[256] - 1.144989013671875).abs() < 1e-15,
            "D[256] = {} statt 1,144989013671875",
            SYNTHESE_FENSTER[256]
        );
        // Der Wechsel passiert genau alle 64 Werte.
        for k in [257usize, 300, 383, 449, 500] {
            assert!(
                SYNTHESE_FENSTER[k] * SYNTHESE_FENSTER[512 - k] < 0.0,
                "D[{k}] und D[{}] haben dasselbe Vorzeichen",
                512 - k
            );
        }
        for k in [256usize, 320, 384, 448] {
            assert_eq!(
                SYNTHESE_FENSTER[k],
                SYNTHESE_FENSTER[512 - k],
                "D[{k}] und D[{}] muessen gleich sein (i & 63 == 0)",
                512 - k
            );
        }
    }
