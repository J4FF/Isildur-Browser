//! DIE GENERIERTEN DATEN DER HUFFMAN-TABELLEN — nur Daten, keine Logik.
//!
//! # WOHER, UND WARUM GENERIERT
//!
//! Die 15 Codebuecher stammen aus `libavcodec/mpegaudiodec_common.c`
//! (`mpa_hufflens` / `mpa_huffsymbols`), maschinell an den Kommentarzeilen
//! („Huffman table 1 - 4 entries" usw.) in Bloecke geteilt. Sie sind hier
//! **nicht abgetippt**, sondern von einem Skript erzeugt — 1378 Laengen
//! und 1378 Symbolpaare sind keine Sache fuer Augen und Finger.
//!
//! # DIE PRUEFUNG, DIE DAS ABSICHERT
//!
//! Fuer **jede** der 15 Gruppen gilt, gemessen und im Test
//! `alle_huffman_baeume_sind_vollstaendig` nachgerechnet:
//!
//! ```text
//! Summe ueber alle Eintraege von 2^(32 - Laenge) == 1 * 2^32
//! ```
//!
//! Die Kraft-Summe eines vollstaendigen Huffman-Baums ist genau 1, und sie
//! ist eine **Ganzzahlpruefung**: bei 32 Nachkomma-Stellen kann sie nur
//! dann stimmen, wenn kein Laengenwert falsch ist. Ein Zahlendreher
//! faellt sofort auf.
//!
//! GEMESSEN, und es hat eine meiner Annahmen widerlegt: ISO-Tabelle 13
//! hat **256** Eintraege, nicht 64. Ich hatte 64 im Kopf. Die Kraft-Summe
//! der ersten 64 Eintraege erreicht 1 *nicht*; die der 256 erreicht 1
//! genau. Wieder dieselbe Lehre wie bei den Vorbis-Codebuechern: eine
//! unplausible Zahl ist ein Befund, kein Randfehler.
//!
//! # DIE ZUORDNUNG ISO-TABELLE -> GRUPPE
//!
//! Die 32 ISO-Tabellen teilen sich 15 Codebuecher: die Tabellen 16..23
//! benutzen **denselben** Baum wie Nummer 14 und unterscheiden sich nur in
//! der Zahl der „linbits", ebenso 24..31 gegenueber Nummer 15. Das ist
//! `ff_mpa_huff_data[32][2]`: `{Gruppe, linbits}`. Tabellen 0, 4 und 14
//! sind leer (Gruppe 0) — kein Encoder benutzt sie.

/// Ein Codebuch: je Eintrag die Codewortlaenge und das Wertepaar (x, y).
pub struct Codebuch {
    /// Die Laengen, in der Reihenfolge der ISO-Tabelle.
    pub laengen: &'static [u8],
    /// Die Wertepaare, in derselben Reihenfolge.
    pub werte: &'static [(u8, u8)],
    /// Die **Codes** je Symbol, wenn die Vergabe nicht kanonisch ist.
    ///
    /// Leer bedeutet: die Codes werden kanonisch vergeben
    /// (`code(Laenge + 1) = (code(Laenge) + Anzahl(Laenge)) * 2`).
    ///
    /// GEMESSENER BEFUND, und er ist der Grund fuer dieses Feld: bei den
    /// Tabellen 24 bis 31 sind die Codes **innerhalb** einer Laenge
    /// **nicht zusammenhaengend**. GEMESSEN an Gruppe 15, 256 Codewoerter,
    /// Kraft-Summe exakt 1:
    /// ```text
    ///   Laenge  4:  5 Codewoerter, Codes  3.. 15   <- Luecke bei 0..2
    ///   Laenge  7: 25 Codewoerter, Codes  4.. 81   <- Luecke
    ///   Laenge 10: 80 Codewoerter, Codes 259..435
    /// ```
    /// Bei einer kanonischen Vergabe waeren sie zusammenhaengend. Die
    /// MP3-Vergabe ist also **nicht** kanonisch, und ein kanonischer
    /// Aufbau kann sie grundsaetzlich nicht reproduzieren — unabhaengig
    /// davon, wie die Symbole in der Liste stehen.
    pub codes: &'static [u32],
}

