/// Der Name ohne das Teilschnitt-Praefix.
///
/// added 03.10.2026. GEMESSEN: `rfc2616.pdf` schreibt
/// `/BaseFont /Times-Roman` **ohne** Praefix, die arXiv-Dateien
/// schreiben `/BaseFont /AECCXO+NimbusRomNo9L-Regu` — sechs
/// Zeichen, ein `+`, dann der Name. Ohne das Abschneiden findet die
/// Tabelle die sechs grossen Schriften nur, wenn sie ohne Praefix
/// eingebettet sind, also praktisch nie.
pub(crate) fn ohne_praefix(name: &str) -> &str {
    match name.find('+') {
        // Nur ein Praefix aus **sechs** Zeichen zaehlt: ein `+` in
        // einem normalen Namen (z. B. in einem Teilschnittnamen wie
        // `Foo+Bar` ohne PDF-Praefix) darf nicht alles davor
        // abschneiden.
        Some(i) if i == 6 && name[..i].bytes().all(|b| b.is_ascii_alphanumeric()) => &name[i + 1..],
        _ => name,
    }
}

/// Ist der Name einer der 14?
pub(crate) fn ist_standard(name: &str) -> bool {
    let kurz = ohne_praefix(name);
    STANDARD14.iter().any(|(n, _)| *n == kurz)
}

/// Die **vollstaendige** Tabelle einer Standard-Schrift, Index
/// `code - 32`.
///
/// added 03.10.2026. `None`, wenn der Name nicht in der Liste steht.
/// Zurueckgegeben wird eine Kopie, weil `Breiten` sie besitzt und die
/// Konstante nicht.
pub(crate) fn tabelle(basisname: &str) -> Option<Vec<f64>> {
    if !ist_standard(basisname) {
        return None;
    }
    Some(
        STANDARD14
            .iter()
            .find(|(n, _)| *n == ohne_praefix(basisname))?
            .1
            .iter()
            .map(|b| *b as f64)
            .collect(),
    )
}

/// Die Zahl der eingetragenen Schriften — 14, und der Test sagt es.
#[cfg(test)]
pub(crate) fn anzahl() -> usize {
    STANDARD14.len()
}

#[cfg(test)]
mod tests {
    use super::*;

    /// DIE GEGENPROBE, und sie ist der Grund, warum diese Datei
    /// ueberhaupt gemessen statt nachgeschlagen wurde.
    ///
    /// added 03.10.2026. Die Werte sind aus `mutool trace` auf
    /// `rfc2616.pdf` Seite 5 abgelesen, wo Times-Roman **ohne**
    /// `/Widths` benutzt wird — dieselbe Lage wie hier. Die Zeichen
    /// sind `R F C sp 2 6 1 6 H T T P` aus der Kopfzeile.
    ///
    /// GEMESSEN:
    ///
    /// ```text
    /// <g unicode="R" x="72" adv=".66700008"/>
    /// <g unicode="F" x="78.603488" adv=".55600008"/>
    /// <g unicode="C" x="84.12133" adv=".66700008"/>
    /// <g unicode=" " x="90.724819" adv=".25"/>
    /// ```
    #[test]
    fn zeiten_roman_stimmt_mit_mutool() {
        // R F C sp 2 6 1 6 H T T P
        let erwartet = [
            667u16, 556, 667, 250, 500, 500, 500, 500, 722, 611, 611, 556,
        ];
        let codes = [82u32, 70, 67, 32, 50, 54, 49, 54, 72, 84, 84, 80];
        let t = tabelle("Times-Roman").expect("Times-Roman ist Standard");
        for (i, code) in codes.iter().enumerate() {
            assert_eq!(t[(*code - 32) as usize] as u16, erwartet[i], "Code {code}");
        }
    }

    /// Es sind **14** Schriften, jede mit 224 Werten.
    #[test]
    fn vierzehn_mit_vierundzwanzig() {
        assert_eq!(anzahl(), 14);
        for (name, t) in &STANDARD14 {
            assert_eq!(t.len(), 224, "{name}");
        }
    }

    /// Courier ist monospaced: 600 fuer **jeden** Code. Das ist die
    /// einzige Tabelle, die man sich merken kann — und damit ein
    /// guter Test dafuer, dass die Tabelle nicht verschoben ist.
    #[test]
    fn courier_ist_monospace() {
        let t = tabelle("Courier").expect("Courier ist Standard");
        assert_eq!(t.len(), 224);
        for (i, w) in t.iter().enumerate() {
            assert_eq!(*w, 600.0, "Index {i} (Code {})", i as u32 + 32);
        }
    }

    /// Das Teilschnitt-Praefix: sechs Zeichen, dann `+`.
    #[test]
    fn praefix_wird_abgeschnitten() {
        assert_eq!(ohne_praefix("Times-Roman"), "Times-Roman");
        assert_eq!(
            ohne_praefix("AECCXO+NimbusRomNo9L-Regu"),
            "NimbusRomNo9L-Regu"
        );
        assert_eq!(ohne_praefix("ABCDEF+Times-Roman"), "Times-Roman");
        // Zu kurz, zu lang, oder ein `+` nicht an Position 6: das
        // ist kein PDF-Praefix und wird nicht abgeschnitten.
        assert_eq!(ohne_praefix("AB+Times-Roman"), "AB+Times-Roman");
        assert_eq!(ohne_praefix("Foo+Bar"), "Foo+Bar");
    }

    /// Eine Schrift, die nicht dabei ist, liefert `None` — und keine
    /// Naeherung.
    #[test]
    fn unbekannte_schrift_ist_none() {
        assert!(tabelle("NimbusRomNo9L-Regu").is_none());
        assert!(tabelle("").is_none());
        assert!(!ist_standard("Helvetica-Nope"));
        assert!(ist_standard("Helvetica"));
    }
}
