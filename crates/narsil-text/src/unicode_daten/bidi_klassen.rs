/// Liefert die Bidi-Klasse eines Zeichens.
///
/// Quelle: DerivedBidiClass.txt (Unicode 15.1.0). Zeichen ausserhalb der
/// Tabelle gibt es nicht — die Tabelle ist lueckenlos bis U+10FFFF.
pub fn bidi_klasse(ch: char) -> BidiKlasse {
    let cp = ch as u32;
    if let Ok(i) = KLASSEN.binary_search_by(|&(a, b, _)| {
        if cp < a {
            std::cmp::Ordering::Greater
        } else if cp > b {
            std::cmp::Ordering::Less
        } else {
            std::cmp::Ordering::Equal
        }
    }) {
        return KLASSEN[i].2;
    }
    BidiKlasse::L
}
