/// Liefert die Line_Break-Klasse eines Zeichens (Binaersuche).
pub fn umbruch_klasse(ch: char) -> Umbruchklasse {
    let cp = ch as u32;
    match BEREICHE.binary_search_by(|(von, _, _)| von.cmp(&cp)) {
        Ok(i) => BEREICHE[i].2,
        Err(0) => Umbruchklasse::Xx,
        Err(i) => {
            if cp <= BEREICHE[i - 1].1 {
                BEREICHE[i - 1].2
            } else {
                Umbruchklasse::Xx // Luecke kann es nach dem Erzeugen nicht geben
            }
        }
    }
}

