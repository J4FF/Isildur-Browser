/// LB30b: [\p{Extended_Pictographic}&\p{Cn}] (unassigned pictographic).
pub fn ext_pict_cn(ch: char) -> bool {
    let cp = ch as u32;
    let t = BEREICHE_EXT_PICT_CN;
    match t.binary_search_by(|(von, _)| von.cmp(&cp)) {
        Ok(_) => true,
        Err(0) => false,
        Err(i) => cp <= t[i - 1].1,
    }
}
