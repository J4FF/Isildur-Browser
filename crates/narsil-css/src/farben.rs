/// Sucht einen Farbnamen (bereits kleingeschrieben erwartet).
/// Rueckgabe: (r, g, b) oder None. Linear ueber 148 Eintraege —
// Begruendung: die Liste ist kurz und fest; eine Hashtabelle waere
/// mehr Code als Gewinn (kein std-Hash noetig, keine Allokation).
pub fn name_suchen(name: &str) -> Option<(u8, u8, u8)> {
    // Begrenzt durch die feste Tabellenlaenge (148).
    for (eintrag, r, g, b) in TABELLE {
        if *eintrag == name {
            return Some((*r, *g, *b));
        }
    }
    None
}

/// Anzahl der Eintraege (der Test sichert 148 zu, M7).
pub fn anzahl() -> usize {
    TABELLE.len()
}
